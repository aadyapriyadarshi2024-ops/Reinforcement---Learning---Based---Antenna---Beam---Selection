function S = build_role1_scenario()
%BUILD_ROLE1_SCENARIO Build the complete Role-1 physical scenario.
%
% Returns a structure S containing:
%   cfg, viewer
%   tx1, tx2, rx1, rx2
%   txArray, rxArray
%   rayModel

cfg = project_config();

if ~isfile(cfg.osmFile)
    error(['Missing OSM map file: %s\n' ...
           'Place the required Berlin OpenStreetMap .osm file in:\n%s'], ...
           cfg.osmFile, pwd);
end

% Display the urban geometry
viewer = siteviewer(Buildings=cfg.osmFile);

% Create transmitter sites
tx1 = txsite( ...
    Latitude=cfg.tx1(1), ...
    Longitude=cfg.tx1(2), ...
    AntennaHeight=cfg.tx1(3), ...
    TransmitterFrequency=cfg.f);

tx2 = txsite( ...
    Latitude=cfg.tx2(1), ...
    Longitude=cfg.tx2(2), ...
    AntennaHeight=cfg.tx2(3), ...
    TransmitterFrequency=cfg.f);

% Create receiver sites
rx1 = rxsite( ...
    Latitude=cfg.rx1(1), ...
    Longitude=cfg.rx1(2), ...
    AntennaHeight=cfg.rx1(3));

rx2 = rxsite( ...
    Latitude=cfg.rx2(1), ...
    Longitude=cfg.rx2(2), ...
    AntennaHeight=cfg.rx2(3));

% Show all four sites
show(tx1);
show(tx2);
show(rx1);
show(rx2);

% Week-1 element model.
% The paper ultimately uses rectangular patch elements.
% CosineAntennaElement is used first because it is simpler to debug.
elem = phased.CosineAntennaElement;

txArray = phased.URA( ...
    Size=[cfg.txRows cfg.txCols], ...
    ElementSpacing=cfg.elementSpacing, ...
    Element=elem);

rxArray = phased.URA( ...
    Size=[cfg.rxRows cfg.rxCols], ...
    ElementSpacing=cfg.elementSpacing, ...
    Element=elem);

% Shooting and bouncing ray (SBR), max one reflection.
rayModel = propagationModel( ...
    "raytracing", ...
    Method="sbr", ...
    MaxNumReflections=cfg.maxReflections);

S = struct();
S.cfg = cfg;
S.viewer = viewer;
S.tx1 = tx1;
S.tx2 = tx2;
S.rx1 = rx1;
S.rx2 = rx2;
S.txArray = txArray;
S.rxArray = rxArray;
S.rayModel = rayModel;
end
